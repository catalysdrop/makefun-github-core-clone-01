// Git core: objects, pkt-line framing and packfiles, implemented on
// node:crypto and node:zlib only. No git binary, no dependency.
//
// Formats follow git itself: an object id is SHA-1 over "<type> <len>\0<data>";
// a packfile is "PACK", version 2, a count, zlib streams and a SHA-1 trailer;
// pkt-line frames are 4 hex digits of total length (0000 flush, 0001 delim).

import { createHash } from 'node:crypto';
import { inflateSync as zlibInflate, deflateSync as zlibDeflate } from 'node:zlib';

export type ObjectType = 'commit' | 'tree' | 'blob' | 'tag';

export interface GitObject {
  readonly type: ObjectType;
  readonly data: Buffer;
}

export const ZERO_OID = '0000000000000000000000000000000000000000';

const TYPE_CODE: Record<ObjectType, number> = { commit: 1, tree: 2, blob: 3, tag: 4 };
const CODE_TYPE: Record<number, ObjectType> = { 1: 'commit', 2: 'tree', 3: 'blob', 4: 'tag' };

export function isOid(value: string): boolean {
  return /^[0-9a-f]{40}$/.test(value);
}

export function hashObject(type: ObjectType, data: Buffer): string {
  const head = Buffer.from(`${type} ${data.length}\0`, 'ascii');
  return createHash('sha1').update(head).update(data).digest('hex');
}

export function objectIdOf(type: ObjectType, data: Uint8Array): string {
  return hashObject(type, Buffer.from(data));
}

// ---------------------------------------------------------------------------
// pkt-line
// ---------------------------------------------------------------------------

export type PktKind = 'data' | 'flush' | 'delim';

export interface Packet {
  readonly kind: PktKind;
  readonly payload: Buffer;
  /** The raw frame bytes (length prefix included), for size checks. */
  readonly raw: Buffer;
}

export function encodePktLine(payload: Buffer | string): Buffer {
  const data = typeof payload === 'string' ? Buffer.from(payload, 'utf8') : payload;
  const total = data.length + 4;
  const head = Buffer.from(total.toString(16).padStart(4, '0'), 'ascii');
  return Buffer.concat([head, data]);
}

export function encodePktLines(lines: Array<string | 'flush' | 'delim'>): Buffer {
  const parts: Buffer[] = [];
  for (const line of lines) {
    if (line === 'flush') parts.push(Buffer.from('0000', 'ascii'));
    else if (line === 'delim') parts.push(Buffer.from('0001', 'ascii'));
    else parts.push(encodePktLine(line));
  }
  return Buffer.concat(parts);
}

/** Decode every pkt-line frame in `buffer`; throws on a malformed frame. */
export function decodePktLines(buffer: Buffer): Packet[] {
  const packets: Packet[] = [];
  let offset = 0;
  while (offset < buffer.length) {
    if (offset + 4 > buffer.length) throw new Error('pkt-line is truncated');
    const head = buffer.subarray(offset, offset + 4).toString('ascii');
    const length = parseInt(head, 16);
    if (Number.isNaN(length) || length < 0 || length > 65520) throw new Error(`bad pkt-line length ${JSON.stringify(head)}`);
    if (length === 0) {
      packets.push({ kind: 'flush', payload: Buffer.alloc(0), raw: buffer.subarray(offset, offset + 4) });
      offset += 4;
      continue;
    }
    if (length === 1) {
      packets.push({ kind: 'delim', payload: Buffer.alloc(0), raw: buffer.subarray(offset, offset + 4) });
      offset += 4;
      continue;
    }
    if (offset + length > buffer.length) throw new Error('pkt-line overruns its buffer');
    packets.push({ kind: 'data', payload: buffer.subarray(offset + 4, offset + length), raw: buffer.subarray(offset, offset + length) });
    offset += length;
  }
  return packets;
}

/**
 * Decode pkt-lines until the first flush (inclusive) and report how many
 * bytes that prefix consumed. Receive-pack bodies carry a binary pack after
 * the flush, which is not pkt-lines and must not be decoded as such.
 */
export function decodePktLinesPrefix(buffer: Buffer): { packets: Packet[]; bytesConsumed: number } {
  const packets: Packet[] = [];
  let offset = 0;
  while (offset < buffer.length) {
    if (offset + 4 > buffer.length) throw new Error('pkt-line is truncated');
    const head = buffer.subarray(offset, offset + 4).toString('ascii');
    const length = parseInt(head, 16);
    if (Number.isNaN(length) || length < 0 || length > 65520) throw new Error(`bad pkt-line length ${JSON.stringify(head)}`);
    if (length === 0) {
      packets.push({ kind: 'flush', payload: Buffer.alloc(0), raw: buffer.subarray(offset, offset + 4) });
      offset += 4;
      break;
    }
    if (length === 1) {
      packets.push({ kind: 'delim', payload: Buffer.alloc(0), raw: buffer.subarray(offset, offset + 4) });
      offset += 4;
      continue;
    }
    if (offset + length > buffer.length) throw new Error('pkt-line overruns its buffer');
    packets.push({ kind: 'data', payload: buffer.subarray(offset + 4, offset + length), raw: buffer.subarray(offset, offset + length) });
    offset += length;
  }
  return { packets, bytesConsumed: offset };
}

/** Incremental pkt-line decoder for streamed bodies. */
export class PktDecoder {
  #buffer = Buffer.alloc(0);

  push(chunk: Buffer): void {
    this.#buffer = Buffer.concat([this.#buffer, chunk]);
  }

  next(): Packet | null {
    if (this.#buffer.length < 4) return null;
    const head = this.#buffer.subarray(0, 4).toString('ascii');
    const length = parseInt(head, 16);
    if (Number.isNaN(length) || length < 0 || length > 65520) throw new Error(`bad pkt-line length ${JSON.stringify(head)}`);
    if (length === 0) {
      const raw = this.#buffer.subarray(0, 4);
      this.#buffer = this.#buffer.subarray(4);
      return { kind: 'flush', payload: Buffer.alloc(0), raw };
    }
    if (length === 1) {
      const raw = this.#buffer.subarray(0, 4);
      this.#buffer = this.#buffer.subarray(4);
      return { kind: 'delim', payload: Buffer.alloc(0), raw };
    }
    if (this.#buffer.length < length) return null;
    const raw = this.#buffer.subarray(0, length);
    const payload = this.#buffer.subarray(4, length);
    this.#buffer = this.#buffer.subarray(length);
    return { kind: 'data', payload, raw };
  }

  finish(): void {
    if (this.#buffer.length > 0) throw new Error('trailing bytes after the last pkt-line');
  }
}

